"""Full test report and per-model fragment generation."""

import os
import platform as _platform
from collections import defaultdict
from datetime import datetime

import pytest

from .models import MODEL_INFO
from .latex import (
    tex_escape, generate_summary_table, generate_detail_table,
    generate_failure_section,
)
from .history import generate_history_table

_script_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


def write_model_fragment(model_id, results, criteria_cache=None, history=None):
    """Write test_results.tex fragment to model doc directory."""
    info = MODEL_INFO.get(model_id)
    if not info or not info['dir']:
        return

    model_dir = os.path.join(_script_dir, info['dir'])
    if not os.path.isdir(model_dir):
        return

    model_name = info['name']
    content = [
        '% Auto-generated by test_results generator',
        f'% Generated: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}',
        '% Do not edit manually --- regenerate with: python -m docs.models.test_results.generator',
        '',
        generate_summary_table(model_id, model_name, results),
        '',
        generate_detail_table(model_id, model_name, results, criteria_cache),
        generate_failure_section(results),
    ]

    if history:
        hist_table = generate_history_table(model_id, history)
        if hist_table:
            content.append('')
            content.append(hist_table)

    path = os.path.join(model_dir, 'test_results.tex')
    with open(path, 'w') as f:
        f.write('\n'.join(content))
    print(f'  Written: {path}')


def generate_traceability_matrix(all_results):
    """Generate a longtable tracing every test to its model (SR 11-7 §4.2)."""
    from collections import defaultdict
    by_model = defaultdict(list)
    for r in all_results:
        by_model[r['model_id']].append(r)

    lines = [
        r'\section{Test Traceability Matrix}',
        '',
        r'The following table maps every executed test to its assigned model '
        r'component, providing evidence of coverage required under SR~11-7 '
        r'\S4.2 and SS1/23.',
        '',
        r'\begin{center}',
        r'\small',
        r'\begin{longtable}{p{2.2cm} p{4.5cm} p{6.5cm} p{1.4cm}}',
        r'    \toprule',
        r'    \textbf{Model} & \textbf{Module} & \textbf{Test Name} & \textbf{Status} \\',
        r'    \midrule',
        r'    \endfirsthead',
        r'    \multicolumn{4}{l}{\emph{(continued from previous page)}} \\',
        r'    \toprule',
        r'    \textbf{Model} & \textbf{Module} & \textbf{Test Name} & \textbf{Status} \\',
        r'    \midrule',
        r'    \endhead',
        r'    \midrule',
        r'    \multicolumn{4}{r}{\emph{(continued on next page)}} \\',
        r'    \endfoot',
        r'    \bottomrule',
        r'    \endlastfoot',
    ]

    model_order = sorted(by_model.keys(), key=lambda m: (
        0 if m.startswith('MKM') else 1 if m == 'CDM-ALL' else 2, m
    ))

    from .latex import tex_escape, result_colour
    from .models import MODEL_INFO

    for mid in model_order:
        model_results = by_model[mid]
        model_name = MODEL_INFO.get(mid, {}).get('name', mid)
        # Sort by nodeid
        model_results = sorted(model_results, key=lambda r: r.get('nodeid', ''))
        first = True
        for r in model_results:
            nodeid = r.get('nodeid', '')
            # Split nodeid into file::test_name
            parts = nodeid.split('::')
            if len(parts) >= 2:
                module = '::'.join(parts[:-1]).split('/')[-1]
                test_name = parts[-1]
            else:
                module = ''
                test_name = nodeid
            mid_cell = tex_escape(mid) if first else ''
            lines.append(
                f'    {mid_cell} & {tex_escape(module)} & '
                f'\\texttt{{{tex_escape(test_name)}}} & {result_colour(r["outcome"])} \\\\'
            )
            first = False
        lines.append(r'    \midrule')

    lines += [
        r'\end{longtable}',
        r'\end{center}',
    ]
    return '\n'.join(lines)


def generate_full_report(all_results, run_timestamp, run_duration,
                         criteria_cache=None, git_sha=None, coverage_pct=None):
    """Generate the standalone test_report.tex."""
    by_model = defaultdict(list)
    for r in all_results:
        by_model[r['model_id']].append(r)

    total = len(all_results)
    passed = sum(1 for r in all_results if r['outcome'] == 'passed')
    failed = sum(1 for r in all_results if r['outcome'] == 'failed')
    skipped = sum(1 for r in all_results if r['outcome'] == 'skipped')
    pass_rate = (passed / total * 100) if total > 0 else 0

    lines = [
        r'\documentclass[11pt,a4paper]{article}',
        r'\newcommand{\doctitle}{Model Test Results Report}',
        r'\newcommand{\docsubtitle}{Automated Test Documentation for Model Governance}',
        r'\newcommand{\docversion}{1.0}',
        f'\\newcommand{{\\docdate}}{{{run_timestamp.strftime("%d-%B-%Y")}}}',
        r'\newcommand{\docauthor}{David K Kelly}',
        r'\input{../shared/mkm_header}',
        r'\usepackage{longtable}',
        '',
        r'\begin{document}',
        r'\mkmtitlepage',
        r'\mkmlegalpage',
        r'\tableofcontents',
        r'\clearpage',
        '',
        r'\section{Executive Summary}',
        '',
        f'This report documents the results of automated model tests run on '
        f'\\textbf{{{run_timestamp.strftime("%d %B %Y at %H:%M:%S")}}}.',
        '',
        r'\begin{table}[H]',
        r'    \centering',
        r'    \caption{Overall Test Results}',
        r'    \label{tab:overall_summary}',
        r'    \begin{tabular}{lr}',
        r'        \toprule',
        f'        Total Tests & {total} \\\\',
        f'        \\textcolor{{green!60!black}}{{Passed}} & {passed} \\\\',
        f'        \\textcolor{{red}}{{Failed}} & {failed} \\\\',
        f'        Skipped & {skipped} \\\\',
        f'        Pass Rate & {pass_rate:.1f}\\% \\\\',
        f'        Total Duration & {run_duration:.2f}s \\\\',
        r'        \bottomrule',
        r'    \end{tabular}',
        r'\end{table}',
        '',
        r'\subsection{Test Environment}',
        '',
        r'\begin{table}[H]',
        r'    \centering',
        r'    \begin{tabular}{ll}',
        r'        \toprule',
        f'        Platform & {tex_escape(_platform.platform())} \\\\',
        f'        Python & {tex_escape(_platform.python_version())} \\\\',
        f'        pytest & {tex_escape(pytest.__version__)} \\\\',
        *(
            [f'        Coverage & {coverage_pct:.1f}\\% \\\\']
            if coverage_pct is not None else []
        ),
        *(
            [f'        Git Commit & \\texttt{{{tex_escape(git_sha[:12])}}} \\\\']
            if git_sha else []
        ),
        r'        \bottomrule',
        r'    \end{tabular}',
        r'\end{table}',
        '',
        r'\subsection{Results by Model}',
        '',
        r'\begin{table}[H]',
        r'    \centering',
        r'    \caption{Test Results by Model}',
        r'    \label{tab:results_by_model}',
        r'    \begin{tabular}{llrrrrr}',
        r'        \toprule',
        r'        \textbf{Model ID} & \textbf{Model Name} & \textbf{Total} & \textbf{Pass} & \textbf{Fail} & \textbf{Skip} & \textbf{Time (s)} \\',
        r'        \midrule',
    ]

    model_order = sorted(by_model.keys(), key=lambda m: (
        0 if m.startswith('MKM') else 1 if m == 'CDM-ALL' else 2, m
    ))

    for mid in model_order:
        model_results = by_model[mid]
        info = MODEL_INFO.get(mid, {'name': mid})
        m_total = len(model_results)
        m_pass = sum(1 for r in model_results if r['outcome'] == 'passed')
        m_fail = sum(1 for r in model_results if r['outcome'] == 'failed')
        m_skip = sum(1 for r in model_results if r['outcome'] == 'skipped')
        m_dur = sum(r['duration'] for r in model_results)
        fail_str = f'\\textcolor{{red}}{{{m_fail}}}' if m_fail > 0 else '0'
        lines.append(
            f'        {tex_escape(mid)} & {tex_escape(info["name"])} & '
            f'{m_total} & {m_pass} & {fail_str} & {m_skip} & {m_dur:.2f} \\\\'
        )

    lines += [
        r'        \bottomrule',
        r'    \end{tabular}',
        r'\end{table}',
        r'\clearpage',
        '',
        generate_traceability_matrix(all_results),
        r'\clearpage',
        '',
    ]

    for mid in model_order:
        if mid == 'PLATFORM':
            continue
        model_results = by_model[mid]
        info = MODEL_INFO.get(mid, {'name': mid})
        safe_mid = tex_escape(mid)
        lines.append(f'\\section{{{tex_escape(info["name"])} ({safe_mid})}}\n')
        lines.append(generate_summary_table(mid, info['name'], model_results))
        lines.append('')
        lines.append(generate_detail_table(mid, info['name'], model_results, criteria_cache))
        lines.append(generate_failure_section(model_results))
        lines.append(r'\clearpage')
        lines.append('')

    if 'PLATFORM' in by_model:
        lines.append(r'\appendix')
        lines.append(r'\section{Platform Infrastructure Tests}')
        lines.append('')
        platform_results = by_model['PLATFORM']
        lines.append(generate_summary_table('PLATFORM', 'Platform Infrastructure', platform_results))
        lines.append('')
        lines.append(generate_detail_table('PLATFORM', 'Platform Infrastructure', platform_results, criteria_cache))
        lines.append(generate_failure_section(platform_results))

    lines.append('')
    lines.append(r'\end{document}')

    report_dir = os.path.join(_script_dir, 'test_results')
    os.makedirs(report_dir, exist_ok=True)
    report_path = os.path.join(report_dir, 'test_report.tex')
    with open(report_path, 'w') as f:
        f.write('\n'.join(lines))
    print(f'\n  Full report: {report_path}')
    return report_path
